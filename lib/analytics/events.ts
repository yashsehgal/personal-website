type ArchiveLinkId = (typeof ARCHIVE_LINKS)[number]["id"];

export type ArchiveClickEventName = `${ArchiveLinkId}_CLICK`;

export const archiveClickEvent = Object.fromEntries(
  ARCHIVE_LINKS.map((link) => [link.id, `${link.id}_CLICK`]),
) as { [Id in ArchiveLinkId]: `${Id}_CLICK` };

export type AnalyticsEventName =
  | (typeof AnalyticsEvent)[keyof typeof AnalyticsEvent]
  | ArchiveClickEventName;

export type AnalyticsProperties = Record<
  string,
  string | number | boolean | null
>;

